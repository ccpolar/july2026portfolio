'use client'

import { useEffect, useRef, useState } from 'react'

import { ButtonLink } from '@/components/Button'
import { type ColorFormat, contrast, formatColor, parseColor, readableOn } from '@/lib/color'
import {
  DEFAULT_PALETTE,
  HARMONIES,
  type Harmony,
  MAX_SWATCHES,
  MIN_SWATCHES,
  type Swatch,
  addSwatch,
  decodePalette,
  encodePalette,
  generatePalette,
} from '@/lib/palette'

import { useColorPicker } from './colorPicker/useColorPicker'
import { Icon } from './icons'
import styles from './PaletteTool.module.css'
import ui from './controls.module.css'
import { STORAGE, USE_COLORS_EVENT, copyText, readStored, writeStored } from './shared'

const FORMATS: { value: ColorFormat; label: string }[] = [
  { value: 'hex', label: 'HEX' },
  { value: 'rgb', label: 'RGB' },
  { value: 'hsl', label: 'HSL' },
  { value: 'cmyk', label: 'CMYK' },
]

/** Body text needs 4.5:1 against its background to be comfortably readable. */
const READABLE = 4.5

/** The value under a swatch: shown in the chosen format, and typed over with
 *  a hex or RGB value to change the colour. */
const Value = ({
  swatch,
  format,
  onChange,
}: {
  swatch: Swatch
  format: ColorFormat
  onChange: (hex: string) => void
}) => {
  const [draft, setDraft] = useState<string | null>(null)
  return (
    <input
      className={styles.value}
      type="text"
      spellCheck={false}
      autoComplete="off"
      aria-label={`${swatch.role} value. Type a hex or RGB colour to change it`}
      value={draft ?? formatColor(swatch.hex, format)}
      onChange={(e) => {
        setDraft(e.target.value)
        const parsed = parseColor(e.target.value)
        if (parsed) onChange(parsed)
      }}
      onFocus={(e) => e.currentTarget.select()}
      onBlur={() => setDraft(null)}
      onKeyDown={(e) => {
        if (e.key === 'Enter') e.currentTarget.blur()
      }}
    />
  )
}

/**
 * A small palette maker, after Colorify: a palette of named roles rather
 * than loose colours, generated by harmony, with the pairs that are safe to
 * set text in listed underneath. The full tool is one button away.
 */
export const PaletteTool = ({ colorifyUrl }: { colorifyUrl: string }) => {
  const [swatches, setSwatches] = useState<Swatch[]>(DEFAULT_PALETTE)
  const [harmony, setHarmony] = useState<Harmony>('any')
  const [format, setFormat] = useState<ColorFormat>('hex')
  const [history, setHistory] = useState<Swatch[][]>([])
  const [loaded, setLoaded] = useState(false)
  const [note, setNote] = useState('')
  // A colour picker fires on every pixel of a drag; those all count as one
  // step back.
  const lastEdit = useRef({ key: '', at: 0 })

  // — The colour picker (Colorify's, shared with the mesh gradient), opened
  //   from whichever swatch was clicked. While it's open every change shows
  //   live; closing it is what counts as one step for Undo. —
  const picker = useColorPicker()
  const [pickingRole, setPickingRole] = useState<Swatch['role'] | null>(null)
  const swatchesNow = useRef(swatches)
  swatchesNow.current = swatches

  const openPicker = (swatch: Swatch, anchor: HTMLElement) => {
    const before = swatchesNow.current
    setPickingRole(swatch.role)
    picker.toggle(anchor, swatch.hex, {
      onChange: (hex) => setSwatches((all) => all.map((s) => (s.role === swatch.role ? { ...s, hex } : s))),
      onClose: (hex, changed) => {
        setPickingRole((role) => (role === swatch.role ? null : role))
        if (!changed) return
        setHistory((h) => [...h.slice(-29), before])
        lastEdit.current = { key: '', at: 0 }
        setNote(`${swatch.role} set to ${hex.toUpperCase()}.`)
      },
    })
  }

  useEffect(() => {
    const fromLink = decodePalette(new URLSearchParams(window.location.search).get('palette'))
    const stored = fromLink ?? decodePalette(readStored(STORAGE.palette))
    if (stored) setSwatches(stored)
    setLoaded(true)
  }, [])

  useEffect(() => {
    if (loaded) writeStored(STORAGE.palette, encodePalette(swatches))
  }, [swatches, loaded])

  const commit = (next: Swatch[], key = '') => {
    const now = Date.now()
    const sameRun = key && key === lastEdit.current.key && now - lastEdit.current.at < 900
    lastEdit.current = { key, at: now }
    if (!sameRun) setHistory((h) => [...h.slice(-29), swatches])
    setSwatches(next)
  }

  const setHex = (index: number, hex: string) =>
    commit(
      swatches.map((s, i) => (i === index ? { ...s, hex } : s)),
      `edit-${index}`,
    )

  const generate = () => {
    commit(generatePalette(harmony, swatches))
    setNote('New palette.')
  }

  const undo = () => {
    const previous = history[history.length - 1]
    if (!previous) return
    setHistory((h) => h.slice(0, -1))
    setSwatches(previous)
    lastEdit.current = { key: '', at: 0 }
    setNote('Went back one step.')
  }

  const copyValue = async (swatch: Swatch) => {
    const text = formatColor(swatch.hex, format)
    setNote((await copyText(text)) ? `Copied ${text}.` : 'Could not copy.')
  }

  const copyAll = async () => {
    const text = swatches.map((s) => `${s.role}: ${formatColor(s.hex, format)}`).join('\n')
    setNote((await copyText(text)) ? 'Copied the whole palette.' : 'Could not copy.')
  }

  const share = async () => {
    const url = `${window.location.origin}${window.location.pathname}?palette=${encodePalette(swatches)}#palette`
    setNote((await copyText(url)) ? 'Link copied.' : 'Could not copy the link.')
  }

  const sendToGradient = () => {
    window.dispatchEvent(new CustomEvent(USE_COLORS_EVENT, { detail: swatches.map((s) => s.hex) }))
    document.getElementById('mesh-gradient')?.scrollIntoView()
    setNote('Sent to the mesh gradient.')
  }

  // Every pair of swatches that text can be set in, strongest first.
  const pairs = swatches
    .flatMap((a, i) => swatches.slice(i + 1).map((b) => ({ a, b, ratio: contrast(a.hex, b.hex) })))
    .filter((pair) => pair.ratio >= READABLE)
    .sort((x, y) => y.ratio - x.ratio)
    .slice(0, 8)

  return (
    <div className={styles.tool}>
      <ul className={styles.swatches}>
        {swatches.map((swatch, i) => (
          <li
            key={swatch.role}
            className={styles.swatch}
            style={{ background: swatch.hex, color: readableOn(swatch.hex) }}
          >
            {/* The whole swatch opens the colour picker. */}
            <button
              type="button"
              className={styles.pick}
              aria-label={`Pick the ${swatch.role} colour`}
              aria-haspopup="dialog"
              aria-expanded={pickingRole === swatch.role}
              onClick={(e) => openPicker(swatch, e.currentTarget)}
            />

            <div className={styles.actions}>
              <button
                type="button"
                className={styles.chip}
                aria-pressed={swatch.locked}
                aria-label={`Lock ${swatch.role}`}
                title={swatch.locked ? 'Locked: kept when you generate' : 'Lock this colour'}
                onClick={() =>
                  setSwatches((all) => all.map((s, j) => (j === i ? { ...s, locked: !s.locked } : s)))
                }
              >
                <Icon name={swatch.locked ? 'lock' : 'unlock'} size={14} />
              </button>
              <button
                type="button"
                className={styles.chip}
                aria-label={`Remove ${swatch.role}`}
                title="Remove"
                disabled={swatches.length <= MIN_SWATCHES}
                onClick={() => {
                  commit(swatches.filter((_, j) => j !== i))
                  setNote(`${swatch.role} removed.`)
                }}
              >
                <Icon name="close" size={14} />
              </button>
            </div>

            <div className={styles.meta}>
              <span className={styles.role}>{swatch.role}</span>
              <div className={styles.valueRow}>
                <Value swatch={swatch} format={format} onChange={(hex) => setHex(i, hex)} />
                <button
                  type="button"
                  className={styles.chip}
                  aria-label={`Copy ${swatch.role}`}
                  title="Copy"
                  onClick={() => copyValue(swatch)}
                >
                  <Icon name="copy" size={14} />
                </button>
              </div>
            </div>
          </li>
        ))}
        {swatches.length < MAX_SWATCHES ? (
          <li className={styles.addCell}>
            <button
              type="button"
              className={styles.add}
              onClick={() => {
                commit(addSwatch(swatches))
                setNote('Colour added.')
              }}
            >
              <Icon name="plus" />
              <span>Add</span>
            </button>
          </li>
        ) : null}
      </ul>

      <div className={ui.bar}>
        <div className={ui.barGroup}>
          <label className={styles.select}>
            <span className="sr-only">Harmony</span>
            <select value={harmony} onChange={(e) => setHarmony(e.target.value as Harmony)}>
              {HARMONIES.map((h) => (
                <option key={h.value} value={h.value}>
                  {h.label}
                </option>
              ))}
            </select>
          </label>
          <button type="button" className={`${ui.button} ${ui.primary}`} onClick={generate}>
            <Icon name="shuffle" />
            Random palette
          </button>
          <button type="button" className={ui.button} onClick={undo} disabled={!history.length}>
            <Icon name="undo" />
            Undo
          </button>
        </div>

        <div className={ui.barGroup}>
          <div className={ui.segments} role="group" aria-label="Colour format">
            {FORMATS.map((f) => (
              <button
                key={f.value}
                type="button"
                className={ui.segment}
                aria-pressed={format === f.value}
                onClick={() => setFormat(f.value)}
              >
                {f.label}
              </button>
            ))}
          </div>
          <button type="button" className={ui.button} onClick={copyAll}>
            <Icon name="copy" />
            Copy all
          </button>
          <button type="button" className={ui.button} onClick={share}>
            <Icon name="link" />
            Copy link
          </button>
          <button type="button" className={ui.button} onClick={sendToGradient}>
            <Icon name="gradient" />
            Use in gradient
          </button>
        </div>
      </div>

      <p className={`${ui.note} ${styles.noteArea}`} role="status" aria-live="polite">
        {note}
      </p>

      <div className={styles.pairs}>
        <h3 className={ui.label}>Readable pairings</h3>
        {pairs.length ? (
          <ul className={styles.pairList}>
            {pairs.map(({ a, b, ratio }) => {
              // The lighter of the two is the ground, as it usually is on a page.
              const [ground, text] = contrast(a.hex, '#000000') >= contrast(b.hex, '#000000') ? [a, b] : [b, a]
              return (
                <li
                  key={`${ground.role}-${text.role}`}
                  className={styles.pair}
                  style={{ background: ground.hex, color: text.hex }}
                >
                  <span className={styles.pairSample} aria-hidden="true">
                    Aa
                  </span>
                  <span className={styles.pairText}>
                    {text.role} on {ground.role}
                    <small>{ratio.toFixed(1)}:1</small>
                  </span>
                </li>
              )
            })}
          </ul>
        ) : (
          <p className={ui.hint}>
            No two of these are far enough apart to set text in. Try a darker ink or a lighter surface.
          </p>
        )}
      </div>

      <div className={styles.more}>
        <p>
          This is the pocket version. Colorify shows a palette in proportion, in context, across real
          layouts.
        </p>
        <ButtonLink href={colorifyUrl} variant="soft" withArrow>
          Open the full Colorify
        </ButtonLink>
      </div>
    </div>
  )
}
